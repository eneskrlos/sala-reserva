-- =====================================================================
-- V1 — Esquema inicial de la API de reserva de salas de reuniones
-- =====================================================================

-- Extensión necesaria para el EXCLUDE constraint que mezcla un escalar
-- (sala_id con =) y un rango (tstzrange con &&).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------
-- Usuarios (autenticación JWT)
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(100) NOT NULL UNIQUE,
    password   VARCHAR(100) NOT NULL,          -- hash BCrypt
    rol        VARCHAR(30)  NOT NULL DEFAULT 'USER',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- Salas
-- ---------------------------------------------------------------------
CREATE TABLE salas (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL UNIQUE,
    ubicacion  VARCHAR(200),
    capacidad  INTEGER,
    activa     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_salas_capacidad CHECK (capacidad IS NULL OR capacidad > 0)
);

-- ---------------------------------------------------------------------
-- Reservas
-- ---------------------------------------------------------------------
CREATE TABLE reservas (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_id     BIGINT       NOT NULL REFERENCES salas(id),
    responsable VARCHAR(150) NOT NULL,
    inicio      TIMESTAMPTZ  NOT NULL,
    fin         TIMESTAMPTZ  NOT NULL,
    estado      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVA',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_reservas_rango  CHECK (fin > inicio),
    CONSTRAINT chk_reservas_estado CHECK (estado IN ('ACTIVA', 'CANCELADA'))
);

-- Dos reservas ACTIVAS de la misma sala no pueden solaparse en el tiempo.
-- tstzrange usa por defecto '[)' (inicio inclusivo, fin exclusivo): una
-- reserva que termina justo cuando otra empieza NO se considera solape.
ALTER TABLE reservas
    ADD CONSTRAINT excl_reservas_solape
    EXCLUDE USING gist (
        sala_id              WITH =,
        tstzrange(inicio, fin) WITH &&
    ) WHERE (estado = 'ACTIVA');

-- Índice de apoyo para los filtros por sala y fecha.
CREATE INDEX idx_reservas_sala_inicio ON reservas (sala_id, inicio);
